"""Generates the brick pool in scene_fixed_table.xml (idempotent; rewrites between markers).

  brick1..brick3  on the table (the fixed start layout, slots 1-3)
  brick4..brick13 SPARES, parked far off-scene and frozen by an active weld-to-world
                  (`park_brickK`, body2 omitted = world, anchor = the parking position -- required).
                  brick_spawner.BrickSpawner deactivates the weld and teleports a spare into slot 1
                  or 3 on a controller button; MuJoCo can't add bodies at runtime, so the whole pool
                  is pre-built.
  equality        one inactive `snap_brickA_brickB` weld per pair (brick_snap.BrickSnapper needs all
                  pairs) + the park welds
  keyframe        stand_at_table qpos = the robot block (kept from the existing keyframe) + 7 per brick

Parked far away (x=-30) rather than under the floor: the floor is a plane geom, so a body below it
would be pushed out violently. Contype bit per brick = 2^k, conaffinity from make_brick_dovetail.

Usage: python make_brick_pool.py [scene.xml]   (then copy to <MODEL_DIR>)
"""
import itertools, re, sys

from make_brick_dovetail import affinity, geoms

N_TABLE = 3
N_SPARE = 10
N = N_TABLE + N_SPARE
ROBOT_QPOS = 43

# name -> (pos, quat) for the three table bricks (slots 1-3); spares are parked below
TABLE = {
    1: ("0.28 -0.235 0.78025", None),
    2: ("0.28 -0.07 0.78025", "0.7071068 0 0 0.7071068"),
    3: ("0.28 0.15 0.78025", "0.9659258 0 0 0.258819"),
}
PARK_X, PARK_Z, PARK_DY = -30.0, 1.0, 1.0


def park_pos(k):
    return (PARK_X, (k - N_TABLE - 1) * PARK_DY - 4.5, PARK_Z)


def body(k, aff):
    if k in TABLE:
        pos, quat = TABLE[k]
    else:
        pos, quat = "%g %g %g" % park_pos(k), None
    q = f' quat="{quat}"' if quat else ""
    return (f'    <body name="brick{k}" pos="{pos}"{q}>\n'
            '      <freejoint/>\n'
            '      <geom type="mesh" mesh="yellow_plaex_long" material="plaex_yellow"\n'
            '            quat="0.7071068 0.7071068 0 0" contype="0" conaffinity="0" density="0" group="2"/>\n'
            f'{geoms(k, 1 << k, aff)}\n'
            '    </body>\n')


def bodies():
    aff = affinity(N)
    head = (f'    <!-- BRICK POOL (generated by make_brick_pool.py): brick1-{N_TABLE} on the table, '
            f'brick{N_TABLE + 1}-{N} spares\n'
            '         parked at x=-30 and frozen by the park_brickK welds until brick_spawner.py spawns them. -->\n')
    return head + "".join(body(k, aff) for k in range(1, N + 1))


def equality():
    out = ['    <!-- one inactive stud-snap weld per pair (brick_snap.py), then the parking welds -->']
    for a, b in itertools.combinations(range(1, N + 1), 2):
        out.append(f'    <weld name="snap_brick{a}_brick{b}" body1="brick{a}" body2="brick{b}" '
                   'active="false" solref="0.004 1"/>')
    out.append('    <!-- parked spares: weld to world (body2 omitted); the anchor MUST be the parking position (the default\n         anchor 0 0 0 leaves the weld holding nothing -- the brick just falls) -->')
    for k in range(N_TABLE + 1, N + 1):
        out.append(f'    <weld name="park_brick{k}" body1="brick{k}" anchor="%g %g %g" active="true"/>' % park_pos(k))
    return "\n".join(out) + "\n"


def keyframe_brick_qpos():
    rows = []
    for k in range(1, N + 1):
        if k in TABLE:
            pos, quat = TABLE[k]
            rows.append(f'{pos} {quat or "1 0 0 0"}')
        else:
            rows.append("%g %g %g 1 0 0 0" % park_pos(k))
    return "\n            ".join(rows)


def main(path):
    s = open(path).read()
    B0, B1 = "<!-- POOL:BODIES BEGIN -->", "<!-- POOL:BODIES END -->"
    if B0 not in s:                       # first run: convert the hand-written brick bodies
        a = s.index('    <body name="brick1"')
        b = s.index("  </worldbody>")
        s = s[:a] + f"{B0}\n{B1}\n" + s[b:]
    s = re.sub(re.escape(B0) + ".*?" + re.escape(B1), lambda m: f"{B0}\n{bodies()}    {B1}", s, flags=re.S)

    E0, E1 = "<!-- POOL:EQUALITY BEGIN -->", "<!-- POOL:EQUALITY END -->"
    if E0 not in s:
        s = re.sub(r"<equality>.*?</equality>", f"<equality>\n    {E0}\n    {E1}\n  </equality>", s, flags=re.S)
    s = re.sub(re.escape(E0) + ".*?" + re.escape(E1), lambda m: f"{E0}\n{equality()}    {E1}", s, flags=re.S)

    mo = re.search(r'<key name="stand_at_table"\s+qpos="([^"]*)"', s, re.S)
    robot = " ".join(mo.group(1).split()[:ROBOT_QPOS])
    assert len(robot.split()) == ROBOT_QPOS
    new_q = f'{robot}\n            {keyframe_brick_qpos()}'
    s = s[:mo.start(1)] + new_q + s[mo.end(1):]
    open(path, "w").write(s)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "scene_fixed_table.xml")
