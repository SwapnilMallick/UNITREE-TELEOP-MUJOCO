"""
BrickSpawner: an inventory of spare bricks that can be "spawned" into the two empty-able slots
where brick1 and brick3 rest, on a controller button.

MuJoCo can't add bodies at runtime, so the spares are pre-built free bodies (brick4..brickN in
scene_fixed_table.xml, generated by make_brick_pool.py) parked far off-scene and frozen by an active
weld-to-world (`park_brickK`). Spawning = deactivate that weld and teleport the brick into the slot's
resting pose; re-parking (restock) = teleport back and re-activate it.

A spawn is REFUSED (the spare stays in the inventory) if the slot is not vacant: any other brick's
oriented bounding box overlaps the spawn pose (3-D SAT), or a robot geom is within reach of it
(e.g. a hand hovering over the slot).

Slot poses are read from the scene's `stand_at_table` keyframe (brick1 -> slot 1, brick3 -> slot 3),
so they cannot drift from where those bricks actually rest.

Usage: sp = BrickSpawner(m, key_id); ok, msg = sp.spawn(d, 1); sp.restock(d) on a brick reset.
"""
import numpy as np
import mujoco

# Limit NumPy BLAS threading: _obb_overlap() and _point_box_dist() do matrix operations
# that call BLAS routines (R1.T @ R2, etc.). Without limiting, these hit the same thread
# oversubscription penalty that plagued mink IK (fixed in weighted_arm_ik.py).
try:
    import threadpoolctl
    threadpoolctl.threadpool_limits(1)
except ImportError:
    pass  # threadpoolctl not installed; BLAS will use its default threading

# Brick envelope in the body frame: x from -2.75u to 2.5u (tab tip .. slot face), full width/height
# incl. studs. u = 0.035 m (the mesh scale).
ENV_CENTER = np.array([-0.004375, 0.0, 0.00525])
ENV_HALF = np.array([0.091875, 0.04375, 0.04025])
SPAWN_MARGIN = 0.005          # m, extra clearance demanded around the spawn pose
ROBOT_MARGIN = 0.01           # m, robot geoms this close to the spawn pose block it

SLOT_BRICKS = {1: "brick1", 3: "brick3"}    # slot number -> table brick whose resting pose it is


def _obb_overlap(c1, R1, h1, c2, R2, h2):
    """Separating-axis test for two oriented boxes (centre, 3x3 rotation, half extents)."""
    R = R1.T @ R2                        # R[i, j] = (box1 axis i) . (box2 axis j)
    absR = np.abs(R) + 1e-9
    t1 = R1.T @ (c2 - c1)                # centre offset in box1's axes
    for i in range(3):                   # box1 face axes
        if abs(t1[i]) > h1[i] + absR[i] @ h2:
            return False
    for j in range(3):                   # box2 face axes
        if abs(R[:, j] @ t1) > h2[j] + absR[:, j] @ h1:
            return False
    for i in range(3):                   # 9 edge-edge cross axes
        for j in range(3):
            i1, i2 = (i + 1) % 3, (i + 2) % 3
            j1, j2 = (j + 1) % 3, (j + 2) % 3
            r1 = h1[i1] * absR[i2, j] + h1[i2] * absR[i1, j]
            r2 = h2[j1] * absR[i, j2] + h2[j2] * absR[i, j1]
            if abs(t1[i2] * R[i1, j] - t1[i1] * R[i2, j]) > r1 + r2:
                return False
    return True


def _point_box_dist(p, c, R, h):
    q = R.T @ (p - c)
    return float(np.linalg.norm(np.maximum(np.abs(q) - h, 0.0)))


class BrickSpawner:
    def __init__(self, m, key_id, table_bricks=("brick1", "brick2", "brick3"), spares=None,
                 slot_bricks=SLOT_BRICKS):
        self.m = m
        self.table_bricks = tuple(table_bricks)
        if spares is None:
            spares = []
            i = len(self.table_bricks) + 1
            while mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, f"brick{i}") >= 0:
                spares.append(f"brick{i}")
                i += 1
        self.spares = tuple(spares)
        assert self.spares, "no spare bricks in the scene (run make_brick_pool.py)"

        def qadr(name):
            return int(m.jnt_qposadr[m.body(name).jntadr[0]])

        self._qadr = {n: qadr(n) for n in self.table_bricks + self.spares}
        self._dadr = {n: int(m.jnt_dofadr[m.body(n).jntadr[0]]) for n in self._qadr}
        self._body = {n: m.body(n).id for n in self._qadr}
        self._park_eq, self._park_pose = {}, {}
        for n in self.spares:
            e = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_EQUALITY, f"park_{n}")
            assert e >= 0, f"scene has no park weld for {n} (run make_brick_pool.py)"
            self._park_eq[n] = e
            self._park_pose[n] = m.key_qpos[key_id][self._qadr[n]:self._qadr[n] + 7].copy()
        self.slot_pose = {s: m.key_qpos[key_id][self._qadr[b]:self._qadr[b] + 7].copy()
                          for s, b in slot_bricks.items()}
        self.slots = tuple(sorted(self.slot_pose))

        env = {0, m.body("table").id} | set(self._body.values())
        for i in range(m.nbody):                  # any brick body, spawnable or not
            if m.body(i).name.startswith("brick"):
                env.add(i)
        self._robot_geoms = np.array([g for g in range(m.ngeom)
                                      if m.geom_bodyid[g] not in env and m.geom_contype[g]], int)
        self._parked = list(self.spares)           # inventory, in spawn order
        self._out = set()                          # spares currently in play

    # ------------------------------------------------------------------ state
    @property
    def inventory(self):
        return len(self._parked)

    @property
    def capacity(self):
        return len(self.spares)

    @property
    def in_play(self):
        return tuple(n for n in self.spares if n in self._out)

    # ----------------------------------------------------------------- vacancy
    def _spawn_obb(self, slot):
        p, q = self.slot_pose[slot][:3], self.slot_pose[slot][3:]
        R = np.zeros(9)
        mujoco.mju_quat2Mat(R, q)
        R = R.reshape(3, 3)
        return p + R @ ENV_CENTER, R, ENV_HALF + SPAWN_MARGIN

    def blocker(self, d, slot):
        """Name of whatever occupies the slot's spawn pose, or None if it is vacant."""
        c, R, h = self._spawn_obb(slot)
        for n in self.table_bricks + tuple(self._out):
            b = self._body[n]
            Rb = d.xmat[b].reshape(3, 3)
            cb = d.xpos[b] + Rb @ ENV_CENTER
            if _obb_overlap(c, R, h, cb, Rb, ENV_HALF):
                return n
        for g in self._robot_geoms:
            if _point_box_dist(d.geom_xpos[g], c, R, h) < self.m.geom_rbound[g] + ROBOT_MARGIN:
                return self.m.body(int(self.m.geom_bodyid[g])).name
        return None

    def vacant(self, d, slot):
        return self.blocker(d, slot) is None

    # ----------------------------------------------------------------- actions
    def spawn(self, d, slot):
        """Try to spawn the next spare into `slot`. Returns (ok, message); on refusal nothing
        changes and the spare stays in the inventory."""
        if slot not in self.slot_pose:
            return False, f"no spawn slot {slot}"
        if not self._parked:
            return False, "no spare bricks left (press X to restock)"
        mujoco.mj_forward(self.m, d)
        who = self.blocker(d, slot)
        if who is not None:
            what = "the robot" if not who.startswith("brick") else who
            return False, f"slot {slot} is occupied by {what} - spare kept ({self.inventory} left)"
        name = self._parked.pop(0)
        self._out.add(name)
        d.eq_active[self._park_eq[name]] = 0
        q, v = self._qadr[name], self._dadr[name]
        d.qpos[q:q + 7] = self.slot_pose[slot]
        d.qvel[v:v + 6] = 0.0
        mujoco.mj_forward(self.m, d)
        return True, f"spawned {name} in slot {slot} ({self.inventory} spares left)"

    def restock(self, d):
        """Re-park every spare (teleport home + re-activate its weld) -- inventory back to full.
        Call alongside the table-brick reset; does not touch brick1-3."""
        for n in self.spares:
            q, v = self._qadr[n], self._dadr[n]
            d.qpos[q:q + 7] = self._park_pose[n]
            d.qvel[v:v + 6] = 0.0
            d.eq_active[self._park_eq[n]] = 1
        self._parked = list(self.spares)
        self._out.clear()
        mujoco.mj_forward(self.m, d)
